    old_value JSONB,
    new_value JSONB,
    performed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    result VARCHAR(30) NOT NULL CONSTRAINT chk_sl_result CHECK (result IN ('SUCCESS', 'FAILED')),
    CONSTRAINT chk_sl_object_nullity CHECK (
        (object_id IS NULL AND object_type IS NULL) OR
        (object_id IS NOT NULL AND object_type IS NOT NULL)
    )
);

