-- 6. Bảng voucher_programs (Chương trình voucher)
CREATE TABLE voucher_programs (
    program_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_id BIGINT NOT NULL REFERENCES partners(user_id),
    category_id BIGINT NOT NULL REFERENCES categories(category_id),
    program_name VARCHAR(255) NOT NULL,
    original_price DECIMAL(18,2) NOT NULL CONSTRAINT chk_vp_original_price CHECK (original_price >= 0),
    sale_price DECIMAL(18,2) NOT NULL CONSTRAINT chk_vp_sale_price CHECK (sale_price >= 0),
    discount_amount DECIMAL(18,2) GENERATED ALWAYS AS (original_price - sale_price) STORED,
    issue_quantity INT NOT NULL CONSTRAINT chk_vp_issue_quantity CHECK (issue_quantity > 0),
    sale_start_at TIMESTAMP NOT NULL,
    sale_end_at TIMESTAMP NOT NULL,
    use_start_at TIMESTAMP NOT NULL,
    use_end_at TIMESTAMP NOT NULL,
    display_status VARCHAR(20) NOT NULL CONSTRAINT chk_vp_display_status CHECK (display_status IN ('DRAFT', 'PENDING_APPROVAL', 'PUBLISHED', 'HIDDEN', 'ENDED')),
    CONSTRAINT chk_vp_sale_dates CHECK (sale_end_at > sale_start_at),
    CONSTRAINT chk_vp_use_dates CHECK (use_end_at > use_start_at)
);

-- 7. Bảng voucher_program_branches (Chi nhánh áp dụng chương trình - Bảng trung gian N:N)
CREATE TABLE voucher_program_branches (
    program_id BIGINT NOT NULL REFERENCES voucher_programs(program_id),
    branch_id BIGINT NOT NULL REFERENCES branches(branch_id),
    PRIMARY KEY (program_id, branch_id)
);

