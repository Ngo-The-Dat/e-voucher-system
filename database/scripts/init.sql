    issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,
    applicable_region VARCHAR(150),
    used_at TIMESTAMP,
    discount_amount DECIMAL(18,2) CONSTRAINT chk_iv_discount_amount CHECK (discount_amount IS NULL OR discount_amount >= 0)
);

