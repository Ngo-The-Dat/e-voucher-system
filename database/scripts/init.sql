-- 10. Bảng orders (Đơn hàng)
CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_user_id BIGINT NOT NULL REFERENCES users(user_id),
