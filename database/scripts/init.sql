-- 11. Bảng order_items (Chi tiết đơn hàng)
CREATE TABLE order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id),
    program_id BIGINT NOT NULL REFERENCES voucher_programs(program_id),
    quantity INT NOT NULL CONSTRAINT chk_order_items_quantity CHECK (quantity > 0),
    unit_price DECIMAL(18,2) NOT NULL CONSTRAINT chk_order_items_unit_price CHECK (unit_price >= 0),
    line_total DECIMAL(18,2) GENERATED ALWAYS AS (quantity * unit_price) STORED
);

-- 12. Bảng issued_vouchers (Voucher phát hành)
CREATE TABLE issued_vouchers (
    issued_voucher_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
